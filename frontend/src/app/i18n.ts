export type Key = keyof Dict;
const DICTS: Record<Locale, Dict> = { ko, ja };
let current: Locale = 'ko';

export function setLocale(l: Locale) {
  current = l;
  document.documentElement.lang = l;
}
export const getLocale = () => current;

export function t(key: Key | string, vars?: Record<string, string | number>): string {
  const d = DICTS[current] as Record<string, string>;
  let s = d[key] ?? (ko as Record<string, string>)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  return s;
}
